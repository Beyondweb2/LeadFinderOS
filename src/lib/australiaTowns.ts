/* ══ AUSTRALIAN TOWNS, WITH THEIR STATE (2026-10-21, feat/australia-coverage) ═══════════════════════════════════════
   The Coverage list for Australia, and the rules every path uses to keep a town's STATE with it.

   ⛔ THE STATE TRAVELS WITH THE NAME, EVERYWHERE. Australia repeats town names across states (Perth WA / Perth TAS,
      Maitland NSW / SA, Maryborough QLD / VIC, Portland VIC / NSW, Mount Barker SA / WA — all in this list) and the
      UK shares some of them (Newcastle, Perth). So an Australian Coverage town is ALWAYS written "Name STATE"
      ("Ballarat VIC"): the Coverage row and its key, the Find Leads search ("Ballarat VIC, Australia"), the
      lead's coverage_town and the audit question's town all carry it. Two same-name towns in two states are two
      rows that never mix.
   ⛔ A BARE NAME IS NEVER GUESSED INTO A STATE when it is ambiguous: findAuTown answers 'ambiguous', and the caller
      keeps the town as written (a row of its own), exactly as the UK gazetteer treats two St Ives.

   Data: src/data/australiaTowns.ts (ABS Census 2021 Urban Centres, generated by scripts/build-australia-towns.mjs).
   Pure, no I/O. Edge-reachable: relative imports with .ts only. */
import { AUSTRALIA_TOWNS, AUSTRALIA_TOWNS_SOURCE, type AustraliaStateCode } from '../data/australiaTowns.ts';

export { AUSTRALIA_TOWNS_SOURCE };
export type { AustraliaStateCode };

export const AU_STATE_NAMES: Readonly<Record<AustraliaStateCode, string>> = {
  NSW: 'New South Wales', VIC: 'Victoria', QLD: 'Queensland', SA: 'South Australia',
  WA: 'Western Australia', TAS: 'Tasmania', NT: 'Northern Territory', ACT: 'Australian Capital Territory',
};
export const AU_STATE_CODES = Object.keys(AU_STATE_NAMES) as AustraliaStateCode[];

/* ⛔ THE DEFAULT POPULATION BAND FOR THE AUSTRALIA COVERAGE VIEW (changeable on the page, remembered per session).
   10,000–250,000 = the 120 mid-size urban centres (Ballarat, Toowoomba, Bendigo, Cairns…) where a small business can
   be the one AI names. Above 250,000 are the eleven metropolitan areas (Sydney, Melbourne, Brisbane, Perth, Adelaide,
   Gold Coast, Canberra, Newcastle, Central Coast, Sunshine Coast, Wollongong) — each a city of suburbs, worked
   suburb by suburb rather than as one town. Clear the band to see all 726. Same spirit as the UK's 15k–210k. */
export const AU_BAND_DEFAULT_MIN = 10_000;
export const AU_BAND_DEFAULT_MAX = 250_000;
/** An urban centre this big is a whole metropolitan area: a distance from its centre says nothing about a suburb. */
export const AU_METRO_POPULATION = 250_000;

export interface AuTown {
  /** "Ballarat VIC" — the Coverage row name, its key, the search words and the coverage_town. */
  label: string;
  /** "Ballarat" */
  name: string;
  state: AustraliaStateCode;
  /** "Victoria" */
  stateName: string;
  population: number;
  lat: number;
  lng: number;
  /** The full ABS name when it differs ("Forster - Tuncurry"), shown small beside the town. */
  abs: string | null;
  ucl: string;
}

/** Lowercase, brackets / accents / punctuation gone, "-" as a space (the same shape as inTown's townKey). */
function key(s: string | null | undefined): string {
  return String(s ?? '').replace(/\([^)]*\)/g, ' ').normalize('NFKD').replace(/[̀-ͯ]/g, '').toLowerCase()
    .replace(/&/g, ' and ').replace(/['’]/g, '').replace(/[^a-z0-9 ]/g, ' ').replace(/\s+/g, ' ').trim()
    .replace(/^saint /, 'st ').replace(/^mount /, 'mt ');
}

export const auTownLabel = (name: string, state: AustraliaStateCode) => `${name.trim()} ${state}`;

export const AU_TOWNS: readonly AuTown[] = AUSTRALIA_TOWNS.map(([ucl, name, state, population, lat, lng, abs]) => ({
  label: auTownLabel(name, state), name, state, stateName: AU_STATE_NAMES[state], population, lat, lng, abs, ucl,
}));

const BY_NAME_STATE = new Map<string, AuTown>();
const BY_NAME = new Map<string, AuTown[]>();
for (const t of AU_TOWNS) {
  BY_NAME_STATE.set(key(t.name) + '|' + t.state, t);
  const k = key(t.name);
  BY_NAME.set(k, [...(BY_NAME.get(k) ?? []), t]);
}

const STATE_BY_WORDS = new Map<string, AustraliaStateCode>();
for (const c of AU_STATE_CODES) { STATE_BY_WORDS.set(c.toLowerCase(), c); STATE_BY_WORDS.set(key(AU_STATE_NAMES[c]), c); }
STATE_BY_WORDS.set('vic.', 'VIC'); STATE_BY_WORDS.set('tas.', 'TAS'); STATE_BY_WORDS.set('qld.', 'QLD');

/** A state code from "VIC", "Vic.", "Victoria"…, else null. */
export function auStateCode(s: string | null | undefined): AustraliaStateCode | null {
  const raw = String(s ?? '').trim().toLowerCase();
  return STATE_BY_WORDS.get(raw) ?? STATE_BY_WORDS.get(key(raw)) ?? null;
}

/** The state a 4-digit Australian postcode belongs to (Australia Post ranges), else null. */
export function auStateOfPostcode(pc: string | null | undefined): AustraliaStateCode | null {
  const s = String(pc ?? '').trim();
  if (!/^\d{4}$/.test(s)) return null;
  const n = Number(s);
  if (n >= 800 && n <= 999) return 'NT';
  if ((n >= 200 && n <= 299) || (n >= 2600 && n <= 2618) || (n >= 2900 && n <= 2920)) return 'ACT';
  if (n >= 1000 && n <= 2999) return 'NSW';
  if ((n >= 3000 && n <= 3999) || (n >= 8000 && n <= 8999)) return 'VIC';
  if ((n >= 4000 && n <= 4999) || (n >= 9000 && n <= 9999)) return 'QLD';
  if (n >= 5000 && n <= 5999) return 'SA';
  if (n >= 6000 && n <= 6999) return 'WA';
  if (n >= 7000 && n <= 7999) return 'TAS';
  return null;
}

const STATE_ALT = [...AU_STATE_CODES, ...Object.values(AU_STATE_NAMES), 'Vic\\.', 'Tas\\.', 'Qld\\.']
  .sort((a, b) => b.length - a.length).join('|');
const TOWN_STATE_RE = new RegExp(`^(.+?)[\\s,]+(${STATE_ALT})\\.?$`, 'i');
const SUBURB_STATE_PC_RE = new RegExp(`^(.+?)\\s+(${STATE_ALT})\\s*(\\d{4})?$`, 'i');

/** "Ballarat VIC", "Ballarat, Victoria", "Ballarat VIC, Australia" → { name: "Ballarat", state: "VIC" }; no state → state null. */
export function parseAuTown(text: string | null | undefined): { name: string; state: AustraliaStateCode | null } {
  /* "…, Australia" goes; "South Australia" / "Western Australia" are states and stay. */
  const s = String(text ?? '').replace(/(?<!(?:south|western))[,\s]+australia\s*$/i, '').replace(/\s+/g, ' ').trim();
  const m = TOWN_STATE_RE.exec(s);
  if (m) {
    const state = auStateCode(m[2]);
    const name = m[1].replace(/[,\s]+$/, '').trim();
    if (state && name) return { name, state };
  }
  return { name: s, state: null };
}

/** One listed town for a name (+ state when known); 'ambiguous' when a bare name is in two states; null when unlisted. */
export function findAuTown(name: string | null | undefined, state?: AustraliaStateCode | null): AuTown | 'ambiguous' | null {
  const k = key(name);
  if (!k) return null;
  if (state) return BY_NAME_STATE.get(k + '|' + state) ?? null;
  const hits = BY_NAME.get(k) ?? [];
  return hits.length === 1 ? hits[0] : hits.length > 1 ? 'ambiguous' : null;
}

/** A town as written ("Ballarat VIC", "Ballarat, Victoria", or bare) → its listed town, or 'ambiguous' / null. */
export function findAuTownText(text: string | null | undefined): AuTown | 'ambiguous' | null {
  const t = parseAuTown(text);
  return findAuTown(t.name, t.state);
}

export interface AuAddress { suburb: string | null; state: AustraliaStateCode | null; postcode: string | null; parts: string[] }

/** A Google formattedAddress for Australia: "12 Smith St, Richmond VIC 3121, Australia". The state comes from the
 *  state word, else from the postcode. */
export function parseAuAddress(address: string | null | undefined): AuAddress {
  const parts = String(address ?? '').split(',').map((p) => p.trim()).filter(Boolean);
  while (parts.length && /^australia$/i.test(parts[parts.length - 1])) parts.pop();
  for (let i = parts.length - 1; i >= 0; i--) {
    const m = SUBURB_STATE_PC_RE.exec(parts[i]);
    if (m) {
      const state = auStateCode(m[2]) ?? auStateOfPostcode(m[3]);
      return { suburb: m[1].trim() || null, state, postcode: m[3] ?? null, parts: parts.filter((_, j) => j !== i) };
    }
    const pc = /^(.+?)\s+(\d{4})$/.exec(parts[i]);
    if (pc && auStateOfPostcode(pc[2])) {
      return { suburb: pc[1].trim(), state: auStateOfPostcode(pc[2]), postcode: pc[2], parts: parts.filter((_, j) => j !== i) };
    }
  }
  return { suburb: null, state: null, postcode: null, parts };
}

export const auStateOfAddress = (address: string | null | undefined): AustraliaStateCode | null => parseAuAddress(address).state;

/** Is this an Australian lead: its stored country, or an address that ends in Australia. */
export function isAustralianLead(country: string | null | undefined, address?: string | null): boolean {
  if (/^(australia|au|aus)$/i.test(String(country ?? '').trim())) return true;
  return /(^|,)\s*australia\s*$/i.test(String(address ?? ''));
}

/**
 * The town with its state on, for an Australian lead: a town that already names its state is normalised
 * ("Ballarat, Victoria" → "Ballarat VIC"); a bare one takes the state from the business's address, else from the
 * list when the name is in one state only. Ambiguous and nothing to go on → unchanged (never guessed).
 */
export function withAuState(town: string | null | undefined, address?: string | null): string {
  const t = parseAuTown(town);
  if (!t.name) return '';
  if (t.state) return auTownLabel(t.name, t.state);
  const fromAddress = auStateOfAddress(address);
  if (fromAddress) return auTownLabel(t.name, fromAddress);
  const hit = findAuTown(t.name, null);
  return hit && hit !== 'ambiguous' ? hit.label : t.name;
}

/** Same Australian place: same name AND (when both say) the same state. "Richmond VIC" ≠ "Richmond NSW". */
export function sameAuTown(a: string, b: string): boolean {
  const x = parseAuTown(a), y = parseAuTown(b);
  if (!key(x.name) || key(x.name) !== key(y.name)) return false;
  return !x.state || !y.state || x.state === y.state;
}

/** The Coverage key part for an Australian town: name + state, so two states never share a row. */
export const auCoverageKey = (text: string): string => {
  const t = parseAuTown(text);
  return t.state ? key(t.name) + ' ' + t.state.toLowerCase() : key(t.name);
};
