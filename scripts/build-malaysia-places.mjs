#!/usr/bin/env node
/* Builds src/data/malaysiaPlaces.ts from a GeoNames country dump (2026-10-19, docs/coverage-my-sg-population.md).

   Source: GeoNames, https://download.geonames.org/export/dump/MY.zip (MY.txt inside), licensed CC BY 4.0
   ("GeoNames geographical database", https://www.geonames.org). Run by hand, never at build time:

     node scripts/build-malaysia-places.mjs <path to MY.txt> <download date YYYY-MM-DD>

   ⛔ ONLY GeoNames' OWN FIGURES. A populated place (feature class P) is kept when GeoNames gives it a population
      above 0; nothing is estimated, rounded or borrowed from a neighbour. Historical / abandoned / destroyed places
      (PPLH, PPLQ, PPLW, PPLCH) are left out. The state is GeoNames' admin1 code, named from admin1CodesASCII.
   ⛔ NO ALTERNATE NAMES. GeoNames' alternates attach a village's figure to a town's spelling ("Nilai" is an alternate
      of the village Kampung Baharu Nilai, "Gelugor" of Tasek Glugor across the water), so only the place's own name
      is kept. Known spelling variants are a short hand-kept list in src/lib/malaysiaPlaces.ts. */
import fs from 'node:fs';
import path from 'node:path';

const [, , src, date] = process.argv;
if (!src || !/^\d{4}-\d{2}-\d{2}$/.test(date ?? '')) {
  console.error('usage: node scripts/build-malaysia-places.mjs <MY.txt> <YYYY-MM-DD>');
  process.exit(1);
}

/* GeoNames admin1 codes for MY (admin1CodesASCII.txt, read 2026-10-19). */
const STATE = {
  '01': 'Johor', '02': 'Kedah', '03': 'Kelantan', '04': 'Melaka', '05': 'Negeri Sembilan', '06': 'Pahang',
  '07': 'Perak', '08': 'Perlis', '09': 'Penang', '11': 'Sarawak', '12': 'Selangor', '13': 'Terengganu',
  '14': 'Kuala Lumpur', '15': 'Labuan', '16': 'Sabah', '17': 'Putrajaya',
};
const DROP = new Set(['PPLH', 'PPLQ', 'PPLW', 'PPLCH']);
const key = (s) => s.normalize('NFKD').replace(/[̀-ͯ]/g, '').toLowerCase().replace(/[^a-z0-9 ]/g, ' ').replace(/\s+/g, ' ').trim();

const rows = fs.readFileSync(src, 'utf8').split('\n').filter(Boolean).map((l) => l.split('\t'));
const kept = rows
  .filter((r) => r[6] === 'P' && !DROP.has(r[7]) && Number(r[14]) > 0 && STATE[r[10]])
  .map((r) => ({ id: Number(r[0]), name: r[1], ascii: r[2], state: STATE[r[10]], population: Number(r[14]) }))
  .sort((a, b) => b.population - a.population || a.id - b.id);

const lines = kept.map((p) => {
  const name = p.ascii && key(p.ascii) === key(p.name) ? p.name : p.ascii || p.name;
  return `  [${p.id}, ${JSON.stringify(name)}, ${JSON.stringify(p.state)}, ${p.population}],`;
});

const out = `/* GENERATED by scripts/build-malaysia-places.mjs — do not edit by hand. Rebuild from a fresh GeoNames dump.
   Source: GeoNames (https://www.geonames.org), file MY.txt from https://download.geonames.org/export/dump/MY.zip,
   downloaded ${date}. Licence: Creative Commons Attribution 4.0 (CC BY 4.0) — the Coverage page credits GeoNames.
   Every populated place in Malaysia that GeoNames gives a population above 0: [geonameid, name, state,
   population]. Figures are GeoNames' own, for the place itself (not its district); never edited here. */

export const MALAYSIA_PLACES_SOURCE = {
  label: 'GeoNames geographical database (CC BY 4.0), populated places in Malaysia',
  downloaded: ${JSON.stringify(date)},
  url: 'https://www.geonames.org/',
} as const;

export type MalaysiaPlaceRow = readonly [id: number, name: string, state: string, population: number];

export const MALAYSIA_PLACES: readonly MalaysiaPlaceRow[] = [
${lines.join('\n')}
];
`;
const dest = path.join(path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1')), '..', 'src', 'data', 'malaysiaPlaces.ts');
fs.mkdirSync(path.dirname(dest), { recursive: true });
fs.writeFileSync(dest, out, 'utf8');
console.log(`wrote ${kept.length} places to ${dest} (${Buffer.byteLength(out)} bytes)`);
