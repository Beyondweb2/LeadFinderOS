#!/usr/bin/env node
/* Builds src/data/malaysiaCoverageTowns.ts: the Malaysian towns of 50,000+ that Coverage lists beyond its hand list
   (2026-10-23, feat/find-leads-coverage; record in docs/find-leads-coverage.md).

   Source: GeoNames, https://download.geonames.org/export/dump/MY.zip (MY.txt inside), CC BY 4.0 — the same dump
   scripts/build-malaysia-places.mjs reads. Run by hand, never at build time:

     node scripts/build-malaysia-coverage-towns.mjs <path to MY.txt> <download date YYYY-MM-DD>

   THE RULE, in order, over every populated place GeoNames gives 50,000+ (148 on 2026-10-23):
     1. Already on Coverage's hand list (coverageCountries.ts, aliases included) → not added again.
     2. GeoNames' feature type PPLX ("section of populated place": a suburb) → left out.
     3. A village or estate by its name (Kampung / Kampong / Kg / Taman / Felda / Rumah / Tasek) or a sub-district
        (Mukim) → left out.
     4. A neighbourhood of a metro: inside the in-town radius (inTown.ts townRadiusKm) of the capital or a state
        capital of 500,000+ (Kuala Lumpur, Johor Bahru, Ipoh, Malacca, Kota Bharu, Kuantan, Kota Kinabalu) — a search
        for the metro already covers it; or within 2 km of a place already kept (the same place twice) → left out.
     5. Everything else is added, named as GeoNames names it, with its state.
   ⛔ Never a figure of our own: the population shown is GeoNames' (abroadTownPopulation.ts townPopulation). */
import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';

const [, , src, date] = process.argv;
if (!src || !/^\d{4}-\d{2}-\d{2}$/.test(date ?? '')) {
  console.error('usage: node scripts/build-malaysia-coverage-towns.mjs <MY.txt> <YYYY-MM-DD>');
  process.exit(1);
}
const ROOT = path.join(path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1')), '..');
const lib = (f) => import(pathToFileURL(path.join(ROOT, 'src', 'lib', f)).href);
const { townRadiusKm, kmBetween } = await lib('inTown.ts');
const { resolveCoverageTown } = await lib('coverageCountries.ts');
const dest = path.join(ROOT, 'src', 'data', 'malaysiaCoverageTowns.ts');
/* The list this script wrote last time is not "already listed" (rule 1 is the HAND list only). */
const generated = fs.existsSync(dest) ? new Set([...fs.readFileSync(dest, 'utf8').matchAll(/^\s*\[\d+, "([^"]+)"/gm)].map((m) => m[1])) : new Set();

const STATE = {
  '01': 'Johor', '02': 'Kedah', '03': 'Kelantan', '04': 'Melaka', '05': 'Negeri Sembilan', '06': 'Pahang',
  '07': 'Perak', '08': 'Perlis', '09': 'Penang', '11': 'Sarawak', '12': 'Selangor', '13': 'Terengganu',
  '14': 'Kuala Lumpur', '15': 'Labuan', '16': 'Sabah', '17': 'Putrajaya',
};
const DROP = new Set(['PPLH', 'PPLQ', 'PPLW', 'PPLCH']);
const VILLAGE = /^(kampung|kampong|kg\.?|taman|felda|rumah|tasek|mukim)\b/i;

const big = fs.readFileSync(src, 'utf8').split('\n').filter(Boolean).map((l) => l.split('\t'))
  .filter((r) => r[6] === 'P' && !DROP.has(r[7]) && Number(r[14]) >= 50000 && STATE[r[10]])
  .map((r) => ({ id: Number(r[0]), name: r[2] || r[1], fc: r[7], state: STATE[r[10]], pop: Number(r[14]), lat: Number(r[4]), lng: Number(r[5]) }))
  .sort((a, b) => b.pop - a.pop || a.id - b.id);
const METRO = big.filter((o) => (o.fc === 'PPLC' || o.fc === 'PPLA') && o.pop >= 500000);
const why = { listed: [], pplx: [], village: [], neighbourhood: [], added: [] };
const kept = [];
for (const b of big) {
  const r = resolveCoverageTown('Malaysia', b.name);
  if (r?.listed && !generated.has(r.name)) { why.listed.push(b.name); kept.push(b); continue; }
  if (b.fc === 'PPLX') { why.pplx.push(b.name); continue; }
  if (VILLAGE.test(b.name)) { why.village.push(b.name); continue; }
  const host = METRO.find((o) => o !== b && kmBetween(b, o) <= townRadiusKm(o.pop)) ?? kept.find((o) => kmBetween(b, o) <= 2);
  if (host) { why.neighbourhood.push(`${b.name} (${host.name})`); continue; }
  why.added.push(b); kept.push(b);
}

const out = `/* GENERATED by scripts/build-malaysia-coverage-towns.mjs — do not edit by hand (the rule is in its header).
   Source: GeoNames (https://www.geonames.org), MY.txt from https://download.geonames.org/export/dump/MY.zip, downloaded
   ${date}, CC BY 4.0. The Malaysian places of 50,000+ that are towns (not a suburb, a kampung or a metro's
   neighbourhood) and are not already on Coverage's hand list: [geonameid, name, state]. */

export const MALAYSIA_COVERAGE_TOWNS_SOURCE = { downloaded: ${JSON.stringify(date)}, minPopulation: 50000 } as const;

export const MALAYSIA_COVERAGE_TOWNS: readonly (readonly [id: number, name: string, state: string])[] = [
${why.added.map((b) => `  [${b.id}, ${JSON.stringify(b.name)}, ${JSON.stringify(b.state)}],`).join('\n')}
];
`;
fs.writeFileSync(dest, out, 'utf8');
console.log(`50,000+ places: ${big.length}`);
for (const [k, v] of Object.entries(why)) console.log(`${k}: ${v.length}${k === 'added' ? '' : ' — ' + v.join('; ')}`);
console.log(`wrote ${why.added.length} towns to ${dest}`);
